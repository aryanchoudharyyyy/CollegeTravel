CREATE TABLE ticket_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    active BOOLEAN NOT NULL,
    description VARCHAR(500),
    destination VARCHAR(255) NOT NULL,
    listing_type VARCHAR(255) NOT NULL,
    posted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    posted_by_user_id BIGINT NOT NULL,
    price NUMERIC(38, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    source VARCHAR(255) NOT NULL,
    status VARCHAR(255),
    ticket_class VARCHAR(255),
    travel_date DATE NOT NULL,
    CONSTRAINT ticket_listings_listing_type_check CHECK (
        listing_type IN ('TRAIN_TICKET', 'BUS_TICKET', 'RIDE_SHARE')
    ),
    CONSTRAINT ticket_listings_status_check CHECK (
        status IN ('CONFIRMED', 'RAC', 'WAITLIST', 'NOT_APPLICABLE')
    ),
    CONSTRAINT ticket_listings_pkey PRIMARY KEY (id)
);

CREATE TABLE listing_interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    expressed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    user_id BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,
    CONSTRAINT listing_interests_pkey PRIMARY KEY (id),
    CONSTRAINT ukle7ls7ein213o5c0kwped31hv UNIQUE (listing_id, user_id),
    CONSTRAINT fki7sqnnfov1ttdnro5ay669sw9
        FOREIGN KEY (listing_id) REFERENCES ticket_listings (id)
